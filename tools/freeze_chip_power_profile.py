"""Bind the temperature-conditioned vectorless estimate to deployed hardware."""
import hashlib
import json
import re
import zlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'report/chip_power_20261021'
def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def main():
    package=json.loads((ROOT/'build/keys_eco_20261018_v4/package.json').read_text())
    checkpoint=ROOT/'build/keys_eco_20261018_v4/keys_routed.dcp'
    if sha(checkpoint)!=package['checkpoint_sha256']:raise ValueError('Checkpoint drift')
    for name,key in [('tt_gcs_keys.bit','bit_sha256'),('tt_gcs_keys.xsa','xsa_sha256')]:
        if sha(ROOT/'firmware/keys_20261018'/name)!=package[key]:raise ValueError('Deployed hardware mismatch')
    rows=[]
    for temp in (-40,0,25,40,55,70,85,100,125):
        path=OUT/f'junction_{temp}.rpt';text=path.read_text()
        def field(name):
            found=re.search(r'\|\s*'+re.escape(name)+r'\s*\|\s*([^|]+)\|',text)
            if not found:raise ValueError('Missing report field '+name)
            return found[1].strip()
        if abs(float(field('Junction Temperature (C)'))-temp)>.1:raise ValueError('Junction override not applied')
        if field('Simulation Activity File')!='---':raise ValueError('Unexpected activity source')
        if package['part'] not in text:raise ValueError('Part mismatch')
        rows.append(dict(temperature_c=temp,watts=float(field('Total On-Chip Power (W)')),
                         static_w=float(field('Device Static (W)')),dynamic_w=float(field('Dynamic (W)')),
                         confidence=field('Confidence Level'),report=path.relative_to(ROOT).as_posix(),sha256=sha(path)))
    profile=dict(schema=1,source='VIVADO_VECTORLESS_TEMPERATURE',measured=False,scope='CHIP_PS_PL_ONLY',
        activity='Vivado vectorless/default switching activity; NOT runtime workload tracking',
        energy_scope='Accepted board START until DONE/STOP/error; includes preparation and pauses; excludes subsequent probes',
        exclusions=['external DDR','fan','board peripherals','DC/DC losses'],
        fallback_temperature_c=40,temperature_max_age_ms=3000,calibrated=False,
        hardware_xsa_sha256=package['xsa_sha256'],bit_sha256=package['bit_sha256'],
        checkpoint_sha256=package['checkpoint_sha256'],part=package['part'],points=rows)
    raw=json.dumps(profile,sort_keys=True,separators=(',',':')).encode()
    profile['model_id']=f'{zlib.crc32(raw):08x}'
    (ROOT/'gcs/chip_power_profile.json').write_text(json.dumps(profile,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    header='// Generated by tools/freeze_chip_power_profile.py. VECTORLESS ESTIMATE, NOT MEASURED.\n'
    header+='#ifndef S2C_POWER_PROFILE_H\n#define S2C_POWER_PROFILE_H\n#include <cstdint>\nnamespace s2c { namespace power_profile {\n'
    header+=f'constexpr uint32_t MODEL_ID=0x{profile["model_id"]}u;\nconstexpr unsigned POINTS={len(rows)};\n'
    header+='constexpr float TEMPERATURES[POINTS]={'+','.join(f'{r["temperature_c"]:.1f}f' for r in rows)+'};\n'
    header+='constexpr float WATTS[POINTS]={'+','.join(f'{r["watts"]:.3f}f' for r in rows)+'};\n'
    header+='}}\n#endif\n'
    (ROOT/'src/ps/s2c_roi_app/roi_power_profile.h').write_text(header,encoding='utf-8')
    print(json.dumps(dict(model_id=profile['model_id'],points=rows),indent=2))

if __name__=='__main__':main()
